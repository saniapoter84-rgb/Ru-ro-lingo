// Тренажёр: двадцать повторов на каждую тему теории.
//
// Правило без повторов не превращается в навык, поэтому у каждого урока
// грамматики есть свой блок практики — отдельным заходом после теории, а не
// вперемешку с ней.
//
// Все задания написаны руками. Раньше они собирались генератором из
// строк-случаев: формально корректно, но у всей темы было одно общее
// объяснение на все двадцать ошибок, а подписи к вариантам брались из общей
// таблицы форм. Генератор знает форму и не знает, что именно в ней ловит
// человека, — поэтому строки-случаи убраны, а каждое задание несёт свой
// разбор и свои подписи.
//
// Та же пачка даёт и короткое напоминание: когда тема всплывает по
// интервальному повторению, из неё берутся пять заданий вместо двадцати —
// тот же материал, но на две минуты.

import { GrammarStep } from '../course/types';

export interface DrillPack {
  /** Совпадает с id урока: тренажёр привязан к его теории. */
  id: string;
  /** Что именно отрабатывается — заголовок блока практики. */
  title: string;
  /**
   * Правило в двух-трёх предложениях.
   *
   * Показывается карточкой перед практикой и работает запасным объяснением
   * там, где у задания нет своего.
   */
  rule: string;
  /**
   * Разбор форм темы: что есть что. Из него строится таблица на карточке
   * правила и объяснение ошибки — чем выбранный вариант отличался от
   * нужного. Сюда же выписываются несуществующие формы: «plecez» выглядит
   * безупречно, и сказать «такой формы нет» полезнее, чем промолчать.
   */
  forms?: Record<string, string>;
  /**
   * Таблица для карточки правила, когда её не собрать из `forms`.
   *
   * У морфологии формы зависят от конкретного слова, и по окончанию их не
   * опознать: «câinele» кончается на «-ele» так же, как множественное
   * «casele». Читать такую таблицу полезно, а угадывать по ней при разборе
   * ошибки — нельзя, поэтому она отделена от `forms`.
   */
  table?: { form: string; meaning: string }[];
  /** Слова, которые тема вводит до того, как спросить их в задании. */
  vocabulary?: { ro: string; ru: string }[];
  /**
   * Двадцать заданий темы, написанных руками.
   *
   * У каждого своя формулировка, свой разбор ошибки и свои подписи к
   * вариантам. Полный блок проигрывается целиком, короткое напоминание
   * берёт из него срез.
   */
  tasks: GrammarStep[];
  /** Формулировка задания для преобразований, если она общая на тему. */
  transformInstruction?: string;
  /**
   * Какую форму ждём в заданиях на ввод.
   *
   * Нужно там, где правильных ответов объективно несколько: «пойду» — это
   * и «o să merg», и «voi merge». Не сказать, какая форма нужна, и не
   * засчитать вторую — значит наказать за верный ответ.
   */
  typeHint?: string;
}
