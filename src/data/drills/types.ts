// Тренажёр: практика, которая делается из данных, а не пишется руками.
//
// Правило без повторов не превращается в навык. Двадцать примеров на одну
// тему написать вручную для каждого из сорока уроков нереально — но этого
// и не нужно: грамматическое упражнение это функция от правила и слова.
// Поэтому здесь хранятся только строки-случаи, а сами задания собирает
// генератор: одна и та же строка становится и выбором варианта, и
// преобразованием формы, и вводом руками.
//
// Побочная выгода: то же самое даёт короткое напоминание. Когда тема
// всплывает по интервальному повторению, из пачки берутся пять случаев
// вместо двадцати — тот же материал, но на две минуты.

export interface DrillRow {
  /**
   * Фраза с пропуском «___». Если задана — упражнение идёт в контексте,
   * а не по голым формам. Так полезнее: в жизни форму выбирают внутри
   * предложения, а не в таблице.
   */
  sentence?: string;
  /** Исходная форма для преобразования: ед. ч. → мн. ч., инфинитив → «я». */
  from?: string;
  /** Правильный ответ: то, что встаёт в пропуск или получается из `from`. */
  ro: string;
  /** Русский перевод — он же смысловая подсказка. */
  ru: string;
  /** Правдоподобные неверные формы. Именно правдоподобные: ловушка
   *  должна быть той ошибкой, которую человек реально сделает. */
  traps: string[];
  alt?: string[];
  note?: string;
}

export interface DrillPack {
  /** Совпадает с id урока: тренажёр привязан к его теории. */
  id: string;
  /** Что именно отрабатывается — заголовок блока практики. */
  title: string;
  /**
   * Правило в двух предложениях.
   *
   * Показывается карточкой перед практикой и работает объяснением при
   * каждой ошибке. Без него тренажёр — это угадайка: задание прилетает,
   * ответ оказывается неверным, и человек не понимает почему.
   */
  rule: string;
  /** Формулировка задания для преобразований. */
  transformInstruction?: string;
  rows: DrillRow[];
}
