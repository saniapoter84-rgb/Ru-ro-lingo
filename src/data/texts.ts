// «Живой текст» — настоящие румынские тексты, а не учебные предложения.
//
// Зачем это нужно. Опыт, уровни и проценты — это цифры про приложение, а не
// про язык: они растут, даже когда человек не чувствует изменений. Здесь
// наоборот. Берётся кусок румынского из жизни — записка соседки, меню,
// объявление на вокзале — и приложение честно показывает, сколько слов в
// нём уже узнаётся. Через неделю тот же текст светится заметно ярче, и это
// единственное доказательство прогресса, которое невозможно подделать
// начислением очков.

export interface TextLine {
  ro: string;
  ru: string;
}

export interface LiveText {
  id: string;
  /** Заголовок по-русски: что это за текст в жизни. */
  title: string;
  kind: string;
  emoji: string;
  /** После какой главы «Тропы» текст становится по-настоящему посильным. */
  chapter: number;
  lines: TextLine[];
  /**
   * Имена, города, названия. Считаются понятными всегда: узнать «Cluj»
   * в тексте не заслуга и не задача — учить в нём нечего.
   */
  proper?: string[];
  /**
   * Перевод каждого слова текста. Ключи — слова в нижнем регистре без
   * знаков препинания. Нужен, чтобы тап по слову никогда не молчал:
   * общий словарь подсказок покрывает не всё, а тут покрытие обязано
   * быть стопроцентным.
   */
  gloss: Record<string, string>;
}

