export type PartOfSpeech =
  | 'noun'
  | 'verb'
  | 'adj'
  | 'phrase'
  | 'pron'
  | 'num'
  | 'adv'
  | 'other';

export interface WordEntry {
  /** Слово/фраза на русском — то, что видит пользователь как "вопрос" в RU→RO. */
  ru: string;
  /** Правильный перевод на румынский. */
  ro: string;
  /** Дополнительные варианты, которые тоже засчитываются как верный ответ. */
  alt?: string[];
  pos: PartOfSpeech;
  /** Короткая грамматическая/культурная подсказка. */
  note?: string;
}

export interface Unit {
  id: string;
  title: string;
  emoji: string;
  words: WordEntry[];
}

